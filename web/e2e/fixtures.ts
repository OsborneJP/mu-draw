/** The update banner's Reload button: the only thing that may reload the app. */
export const RELOAD_BUTTON_TEST_ID = 'update-reload-button';

// Runs in every document before any page script.
function installPageGuards({ reloadButtonTestId, appUrl }: { reloadButtonTestId: string; appUrl: string }) {
  type Report = (kind: string, detail: string) => void;
  const report: Report = (kind, detail) =>
    (window as unknown as { __reportGuard?: Report }).__reportGuard?.(kind, detail);
  // Every link in the page (href, form action), resolved as the browser would follow it. A
  // link inside the app is fine; any other goes to the test, which applies the link policy
  // (config/requestPolicy.ts). An SVG <image>'s href is drawn, not followed, so it goes to
  // the image policy instead (Ketcher draws placed images from data: URLs). Namespaced
  // xlink:href is read when its element is added (MutationObserver's attributeFilter can't
  // name it); the others also when they change.
  const LINK_ATTRIBUTES = ['href', 'action', 'formaction'];
  const XLINK = 'http://www.w3.org/1999/xlink';
  const SVG = 'http://www.w3.org/2000/svg';
  type ReportUrl = (where: string, url: string) => void;
  const reportLink = (element: Element, attribute: string, value: string) => {
    let url = value;
    try {
      url = new URL(value, element.baseURI).href;
    } catch {
      // Reported as written; the test side can't parse it either.
    }
    if (url.startsWith(appUrl)) return;
    const reporters = window as unknown as { __reportLink?: ReportUrl; __reportImageSource?: ReportUrl };
    const image = element.namespaceURI === SVG && element.localName === 'image';
    (image ? reporters.__reportImageSource : reporters.__reportLink)?.(`${element.tagName}[${attribute}]`, url);
  };
  const checkElement = (element: Element) => {
    for (const name of LINK_ATTRIBUTES) {
      const value = element.getAttribute(name);
      if (value !== null) reportLink(element, name, value);
    }
    const xlink = element.getAttributeNS(XLINK, 'href');
    if (xlink !== null) reportLink(element, 'xlink:href', xlink);
  };
  const checkTree = (node: Node) => {
    if (!(node instanceof Element)) return;
    checkElement(node);
    node.querySelectorAll('*').forEach(checkElement);
  };
  new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'attributes') checkElement(record.target as Element);
      else record.addedNodes.forEach(checkTree);
    }
  }).observe(document, { subtree: true, childList: true, attributes: true, attributeFilter: LINK_ATTRIBUTES });
  addEventListener('securitypolicyviolation', (e) =>
    report('csp', `${e.violatedDirective} blocked ${e.blockedURI}`),
  );
  addEventListener('editor-error', (e) => report('editor-error', String((e as CustomEvent).detail)));
  addEventListener('sw-error', (e) => report('sw-error', String((e as CustomEvent).detail)));
  // The app may leave the page, or tell a waiting service worker (a new build) to take
  // over, only after a real click on the update banner's Reload button. Either one
  // without it would lose or break a drawing mid-session, so it is reported and stopped.
  // Playwright's own goto() and reload() are browser-initiated and fire no navigate event.
  let reloadClicked = false;
  document.addEventListener(
    'click',
    (e) => {
      const target = e.target instanceof Element ? e.target : null;
      if (e.isTrusted && target?.closest(`[data-testid="${reloadButtonTestId}"]`)) reloadClicked = true;
    },
    true,
  );
  navigation.addEventListener('navigate', (e) => {
    if (e.destination.sameDocument || e.downloadRequest !== null) return;
    if (e.navigationType === 'reload' && reloadClicked) return;
    e.preventDefault();
    report('navigation', `${e.navigationType} to ${e.destination.url} without a click on Reload`);
  });
  // A new tab's about:blank is not a secure context and has no ServiceWorker.
  if (typeof ServiceWorker !== 'undefined') {
    const postMessage = ServiceWorker.prototype.postMessage as (this: ServiceWorker, ...args: unknown[]) => void;
    ServiceWorker.prototype.postMessage = function (this: ServiceWorker, ...args: unknown[]) {
      const message = args[0] as { type?: unknown } | null;
      if (message?.type === 'SKIP_WAITING' && !reloadClicked) {
        report('takeover', 'a waiting service worker was told to take over without a click on Reload');
        return;
      }
      postMessage.apply(this, args);
    } as ServiceWorker['postMessage'];
  }
  const once = (name: string) =>
    new Promise<true>((resolve) => addEventListener(name, () => resolve(true), { once: true }));
  // Records every key that gets past window's capture phase (where the app blocks
  // Ketcher's debug shortcut) to the document.
  const keysAtDocument: string[] = [];
  document.addEventListener(
    'keydown',
    (e) => keysAtDocument.push(`${e.altKey ? 'Alt+' : ''}${e.shiftKey ? 'Shift+' : ''}${e.code}`),
    true,
  );
  // Ketcher calls the app's onInit twice (src/editor/KetcherEditor.tsx).
  let inits = 0;
  const secondInit = new Promise<true>((resolve) =>
    addEventListener('editor-init', () => {
      if (++inits === 2) resolve(true);
    }),
  );
  Object.assign(window, {
    __secondInit: secondInit,
    __keysAtDocument: keysAtDocument,
    __editorReady: once('editor-ready'),
    __indigoReady: once('struct-service-initialized'),
    __swRegistered: once('sw-registered'),
  });
}

export interface App {
  server: AppServer;
  /** The current browser and its page; relaunch() replaces both. */
  context: BrowserContext;
  page: Page;
  /** Every request seen (page, workers and service worker), in order. */
  requests: Request[];
  /** Every problem the guards saw; the fixture asserts it is empty after the test. */
  problems: string[];
  /** Rejects on the first problem, so a wait on an event that will never come (e.g. Indigo
   * readiness after its wasm was blocked) fails at once instead of at the test deadline. */
  failed: Promise<never>;
  /** Close the browser and start it again on the same profile, as a student quitting and
   * relaunching the app would. The new page is blank; every guard applies to it. */
  relaunch(): Promise<void>;
  /** Open another tab in the same browser (the popup guard allows only these). */
  newPage(): Promise<Page>;
}

export const test = base.extend<{ app: App; buildCopy: boolean; browserArgs: string[] }>({
  /** Serve a copy of the build that the test may change (publishSecondBuild). */
  buildCopy: [false, { option: true }],
  /** Chromium's command-line switches, such as WebGL turned off (the 3D view). */
  browserArgs: [[], { option: true }],
  app: async ({ buildCopy, browserArgs }, use, testInfo) => {
    const server = await startServer(buildCopy ? testInfo.outputPath('dist') : undefined);
    const problems: string[] = [];
    let failNow: (error: Error) => void = () => {};
    const failed = new Promise<never>((_resolve, reject) => {
      failNow = reject;
    });
    failed.catch(() => {}); // only observed when a test races against it
    const addProblem = (problem: string) => {
      problems.push(problem);
      failNow(new Error(`guard tripped: ${problem}`));
    };
    const requests: Request[] = [];
    const origin = new URL(server.url).origin;
    const watch = (page: Page) => {
      page.on('pageerror', (error) => addProblem(`pageerror: ${error.message}`));
      page.on('websocket', (ws) => addProblem(`websocket: ${ws.url()}`));
    };
    const profile = testInfo.outputPath('profile');
    let pagesOpening = 0;
    const launch = async () => {
      // A fresh persistent profile: not incognito (Chrome reports 'in-incognito' as not
      // installable) and with no service worker left over from an earlier run. Full
      // Chromium, because the headless shell stubs the installability check.
      const context = await chromium.launchPersistentContext(profile, {
        channel: 'chromium',
        headless: true,
        args: browserArgs,
      });
      await context.exposeFunction('__reportGuard', (kind: string, detail: string) => {
        addProblem(`${kind}: ${detail}`);
      });
      await context.exposeFunction('__reportLink', (where: string, url: string) => {
        let problem: string | null;
        try {
          problem = linkProblem(url, server.url);
        } catch {
          problem = 'unparseable';
        }
        if (problem) addProblem(`link (${problem}) ${where}: ${url}`);
      });
      await context.exposeFunction('__reportImageSource', (where: string, url: string) => {
        let problem: string | null;
        try {
          problem = imageSourceProblem(url, server.url);
        } catch {
          problem = 'unparseable';
        }
        // A data: URL can be megabytes; its start says what it is.
        if (problem) addProblem(`image source (${problem}) ${where}: ${url.slice(0, 80)}`);
      });
      await context.addInitScript(installPageGuards, { reloadButtonTestId: RELOAD_BUTTON_TEST_ID, appUrl: server.url });
      context.on('request', (request) => {
        requests.push(request);
        const problem = requestProblem(request.url(), server.url);
        if (problem) addProblem(`request (${problem}): ${request.url()}`);
      });
      context.on('response', (response) => {
        if (new URL(response.url()).origin === origin && response.status() >= 400) {
          addProblem(`HTTP ${response.status()}: ${response.url()}`);
        }
      });
      const page = context.pages()[0] ?? (await context.newPage());
      watch(page);
      context.on('page', (opened) => {
        if (pagesOpening > 0) pagesOpening -= 1;
        else addProblem(`popup: ${opened.url()}`);
        watch(opened);
      });
      return { context, page };
    };
    const app: App = {
      server,
      ...(await launch()),
      requests,
      problems,
      failed,
      relaunch: async () => {
        await app.context.close();
        Object.assign(app, await launch());
      },
      newPage: async () => {
        pagesOpening += 1;
        return app.context.newPage();
      },
    };
    await use(app);
    await app.context.close();
    await server.close();
    expect(problems, 'guards').toEqual([]);
  },
});

/** Load the app and wait until Ketcher and its Indigo engine are both ready. */
export async function openEditor(app: App): Promise<void> {
  await app.page.goto(app.server.url);
  await waitForEditor(app);
}

export async function waitForEditor(app: App, page: Page = app.page): Promise<void> {
  const ready = page.evaluate(() => {
    const w = window as unknown as { __editorReady: Promise<true>; __indigoReady: Promise<true> };
    return Promise.all([w.__editorReady, w.__indigoReady]);
  });
  await Promise.race([ready, app.failed]);
}

/** Wait until the service worker is installed (precache complete) and active. Fails at
 * once if the install fails, instead of hanging like navigator.serviceWorker.ready. */
export async function waitForServiceWorker(app: App): Promise<void> {
  const installed = app.page.evaluate(async () => {
    await (window as unknown as { __swRegistered: Promise<true> }).__swRegistered;
    const registration = await navigator.serviceWorker.getRegistration();
    if (!registration) throw new Error('service worker registered but no registration found');
    if (registration.active) return;
    const worker = registration.installing ?? registration.waiting;
    if (!worker) throw new Error('registration has no installing or waiting worker');
    await new Promise<void>((resolve, reject) => {
      const settle = () => {
        if (worker.state === 'activated') resolve();
        if (worker.state === 'redundant') reject(new Error('service worker install failed'));
      };
      worker.addEventListener('statechange', settle);
      settle();
    });
  });
  await Promise.race([installed, app.failed]);
}

export interface InstallabilityError {
  errorId: string;
  errorArguments: { name: string; value: string }[];
}

/** Chrome's own verdict on whether the page can be installed as an app. */
export async function installabilityErrors(app: App): Promise<InstallabilityError[]> {
  const cdp = await app.context.newCDPSession(app.page);
  const result = (await cdp.send('Page.getInstallabilityErrors')) as {
    installabilityErrors: InstallabilityError[];
  };
  await cdp.detach();
  return result.installabilityErrors;
}

/** The manifest Chrome loaded for the page, with URLs resolved. */
export async function appManifest(app: App): Promise<{ scope: string; startUrl: string; id: string }> {
  const cdp = await app.context.newCDPSession(app.page);
  const { url, data } = (await cdp.send('Page.getAppManifest')) as { url: string; data: string };
  await cdp.detach();
  const raw = JSON.parse(data) as { scope: string; start_url: string; id: string };
  const resolve = (value: string) => new URL(value, url).href;
  return { scope: resolve(raw.scope), startUrl: resolve(raw.start_url), id: resolve(raw.id) };
}

/** Fetch a WebAssembly file from the page and compile it, as an engine loader would. */
export async function fetchAndCompileWasm(page: Page, url: string) {
  return page.evaluate(async (wasmUrl) => {
    const response = await fetch(wasmUrl);
    const contentType = response.headers.get('content-type');
    const module = await WebAssembly.compileStreaming(response);
    return { status: response.status, contentType, exports: WebAssembly.Module.exports(module).length };
  }, url);
}

/** Visit once, wait for the precache, then cut the network (and, locally, stop the server)
 * and reload: from here on everything must come from the service worker. */
export async function goOffline(app: App): Promise<void> {
  await openEditor(app);
  await waitForServiceWorker(app);
  if (app.server.local) await app.server.close();
  await app.context.setOffline(true);
  await app.page.reload();
  await waitForEditor(app);
}

/** Call before a change to the drawing; the function it returns resolves with the text
 * autosave stores for that change, under this build's own key. */
export async function nextAutosave(page: Page): Promise<() => Promise<string>> {
  await page.evaluate((key) => {
    (window as unknown as { __nextSave: Promise<string> }).__nextSave = new Promise((resolve) => {
      const setItem = Storage.prototype.setItem;
      Storage.prototype.setItem = function (this: Storage, name: string, value: string) {
        setItem.call(this, name, value);
        if (name !== key) return;
        Storage.prototype.setItem = setItem;
        resolve(value);
      };
    });
  }, autosaveKey(resolveBase()));
  return () => page.evaluate(() => (window as unknown as { __nextSave: Promise<string> }).__nextSave);
}


const WEB_DIR = fileURLToPath(new URL('..', import.meta.url));
const FIXTURES_DIR = fileURLToPath(new URL('../../tests/fixtures/', import.meta.url));

export interface AppServer {
  /** The app's URL, ending with the base path. */
  url: string;
  /** The build folder served, when it is the test's own copy (see `buildCopy`). */
  copy?: string;
  /** True when the test controls the server (local runs). */
  local: boolean;
  close(): Promise<void>;
}

/** Serve the build: DIST_DIR, or a copy of it in `copy` that the test may change. */
export async function startServer(copy?: string): Promise<AppServer> {
  const remote = process.env.SMOKE_URL;
  if (remote) {
    if (copy) throw new Error('a deployed site cannot serve a copy of the build');
    return { url: remote, local: false, close: async () => {} };
  }
  const dist = resolve(WEB_DIR, process.env.DIST_DIR ?? 'dist');
  if (copy) cpSync(dist, copy, { recursive: true });
  const server = await preview({
    configFile: false,
    root: WEB_DIR,
    base: resolveBase(),
    // 'mpa': a missing file is a 404, as on Apache, not index.html.
    appType: 'mpa',
    logLevel: 'warn',
    // Vite's preview reads each file from disk per request, so a test can change the copy.
    build: { outDir: copy ?? dist },
    // Like Apache: the CSP header covers every file, including sw.js and the Indigo worker,
    // and the RDKit worker gets its own (web/csp-workers.json).
    plugins: [cspHeaders(resolveBase())],
    preview: { host: '127.0.0.1', port: 0, strictPort: true },
  });
  const url = server.resolvedUrls?.local[0];
  if (!url) throw new Error('preview server did not report a URL');
  let closing: Promise<void> | undefined;
  // Idempotent: the offline test stops the server itself; the fixture stops it again.
  return { url, copy, local: true, close: () => (closing ??= server.close()) };
}

/** Turn the served copy into a newly deployed build, as a deploy would: index.html gains a
 * marker, and sw.js lists it under a new revision. The browser's next update check then
 * finds a new service worker, which precaches the new index.html. */
export function publishSecondBuild(server: AppServer): void {
  if (!server.copy) throw new Error("publishSecondBuild needs test.use({ buildCopy: true })");
  const html = join(server.copy, 'index.html');
  writeFileSync(html, readFileSync(html, 'utf8').replace('<head>', `<head><meta name="${BUILD_MARKER}">`));
  const sw = join(server.copy, 'sw.js');
  const source = readFileSync(sw, 'utf8');
  const entry = /\{url:"index\.html",revision:"[^"]+"\}/g;
  const found = source.match(entry);
  if (found?.length !== 1) throw new Error(`sw.js: expected one index.html precache entry, found ${found?.length ?? 0}`);
  writeFileSync(sw, source.replace(entry, `{url:"index.html",revision:"second-build"}`));
}


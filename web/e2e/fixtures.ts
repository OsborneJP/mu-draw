/** An init script (context.addInitScript): an RDKit worker's replies reach the app only
 * while not held, so a test decides when RDKit "answers": window.__holdRdkit(name) and
 * window.__releaseRdkit(name), by worker name ('rdkit', the default, for the properties;
 * 'rdkit-nmr' for the NMR preview, which may be held before it starts).
 * window.__heldRdkit(name) counts the replies held now. */
export function holdableRdkitReplies() {
  const RealWorker = window.Worker;
  const holding = new Set<string>();
  const queues = new Map<string, { held: MessageEvent[]; release: () => void }>();
  Object.assign(window, {
    __holdRdkit: (name = 'rdkit') => holding.add(name),
    __releaseRdkit: (name = 'rdkit') => {
      holding.delete(name);
      queues.get(name)?.release();
    },
    __heldRdkit: (name = 'rdkit') => queues.get(name)?.held.length ?? 0,
  });
  window.Worker = class extends RealWorker {
    constructor(url: string | URL, options?: WorkerOptions) {
      super(url, options);
      const name = options?.name ?? '';
      if (!name.startsWith('rdkit')) return;
      const held: MessageEvent[] = [];
      let appHandler: ((event: MessageEvent) => void) | null = null;
      // The app sets worker.onmessage after construction; deliver through this filter.
      RealWorker.prototype.addEventListener.call(this, 'message', (event: Event) => {
        if (holding.has(name)) held.push(event as MessageEvent);
        else appHandler?.(event as MessageEvent);
      });
      Object.defineProperty(this, 'onmessage', {
        get: () => appHandler,
        set: (handler: ((event: MessageEvent) => void) | null) => (appHandler = handler),
      });
      queues.set(name, { held, release: () => held.splice(0).forEach((event) => appHandler?.(event)) });
    }
  };
}

/** An init script (context.addInitScript): Indigo's worker's replies reach Ketcher only while
 * not held, so a test decides when Indigo "answers" (images, conversions, InChIKeys):
 * window.__holdIndigo(), window.__releaseIndigo(), and window.__heldIndigo() counts the
 * replies held now. */
export function holdableIndigoReplies() {
  const RealWorker = window.Worker;
  let holding = false;
  const held: MessageEvent[] = [];
  let release = () => {};
  Object.assign(window, {
    __holdIndigo: () => (holding = true),
    __releaseIndigo: () => {
      holding = false;
      release();
    },
    __heldIndigo: () => held.length,
  });
  window.Worker = class extends RealWorker {
    constructor(url: string | URL, options?: WorkerOptions) {
      super(url, options);
      if (!String(url).includes('indigoWorker')) return;
      let ketcherHandler: ((event: MessageEvent) => void) | null = null;
      // ketcher-standalone sets worker.onmessage after construction; deliver through this filter.
      RealWorker.prototype.addEventListener.call(this, 'message', (event: Event) => {
        if (holding) held.push(event as MessageEvent);
        else ketcherHandler?.(event as MessageEvent);
      });
      Object.defineProperty(this, 'onmessage', {
        get: () => ketcherHandler,
        set: (handler: ((event: MessageEvent) => void) | null) => (ketcherHandler = handler),
      });
      release = () => held.splice(0).forEach((event) => ketcherHandler?.(event));
    }
  };
}

/** An init script (context.addInitScript): the biochem worker's replies reach the app only
 * while not held, and its requests are counted. window.__holdBiochem(),
 * window.__releaseBiochem(), window.__heldBiochem() counts the replies held now, and
 * window.__biochemRequests() the requests (not the library) posted to it so far, and
 * window.__biochemWorkers() how many biochem workers have started. */
export function holdableBiochemReplies() {
  const RealWorker = window.Worker;
  let holding = false;
  let requests = 0;
  let started = 0;
  const held: MessageEvent[] = [];
  let release = () => {};
  Object.assign(window, {
    __holdBiochem: () => (holding = true),
    __releaseBiochem: () => {
      holding = false;
      release();
    },
    __heldBiochem: () => held.length,
    __biochemRequests: () => requests,
    __biochemWorkers: () => started,
  });
  window.Worker = class extends RealWorker {
    constructor(url: string | URL, options?: WorkerOptions) {
      super(url, options);
      if (options?.name !== 'biochem') return;
      started += 1;
      let appHandler: ((event: MessageEvent) => void) | null = null;
      // The app sets worker.onmessage after construction; deliver through this filter.
      RealWorker.prototype.addEventListener.call(this, 'message', (event: Event) => {
        if (holding) held.push(event as MessageEvent);
        else appHandler?.(event as MessageEvent);
      });
      Object.defineProperty(this, 'onmessage', {
        get: () => appHandler,
        set: (handler: ((event: MessageEvent) => void) | null) => (appHandler = handler),
      });
      const post = RealWorker.prototype.postMessage;
      this.postMessage = (message: { kind?: string }, ...rest: never[]) => {
        if (message?.kind === 'compute') requests += 1;
        post.call(this, message, ...rest);
      };
      release = () => held.splice(0).forEach((event) => appHandler?.(event));
    }
  };
}

interface Ket {
  root: { nodes: { $ref?: string }[] };
  [name: string]: unknown;
}

/** Each atom's label and position relative to the drawing's lower-left corner, sorted.
 * Ketcher moves the whole drawing without a change event (it centres a loaded drawing,
 * and shifts everything when a drawing nears the canvas edge), so a saved copy can sit
 * elsewhere on the canvas than the live drawing; Redo also renumbers atoms. Rounded,
 * since loading rescales bonds to (almost exactly) the same length. */
export function shape(text: string): string[] {
  const parsed = JSON.parse(text) as Ket;
  const atoms = parsed.root.nodes
    .filter((node) => node.$ref)
    .flatMap((node) => (parsed[node.$ref!] as { atoms: { label: string; location: number[] }[] }).atoms);
  const x0 = Math.min(...atoms.map((a) => a.location[0]));
  const y0 = Math.min(...atoms.map((a) => a.location[1]));
  const round = (v: number) => (Math.abs(v) < 5e-5 ? 0 : v).toFixed(4);
  return atoms.map((a) => `${a.label} ${round(a.location[0] - x0)} ${round(a.location[1] - y0)}`).sort();
}

/** The live drawing is the expected one: same structure (stereo included), and the same
 * atoms in the same places relative to each other. */
export async function expectDrawing(page: Page, expected: { inchikey: string; ket: string }) {
  expect(await inchiKey(page)).toBe(expected.inchikey);
  expect(shape(await ket(page))).toEqual(shape(expected.ket));
}

/** Steps Ketcher can undo and redo (not in its published types, but stable in 3.18). */
export async function history(page: Page): Promise<{ undo: number; redo: number }> {
  return page.evaluate(() =>
    (window.ketcher!.editor as unknown as { historySize(): { undo: number; redo: number } }).historySize(),
  );
}

/** Ketcher's display settings, as its settings service holds them. */
export function ketcherSettings(page: Page): Promise<Record<string, unknown>> {
  return page.evaluate(() => ({ ...window.ketcher!.settingsService!.getSettings() }));
}

/** A length set in Ketcher's settings, in CSS pixels at print size (1 in is 96 CSS px, 72 pt). */
export function cssPixels(value: number, unit: string): number {
  const perUnit: Record<string, number> = { px: 1, pt: 96 / 72, inch: 96, cm: 96 / 2.54 };
  if (!(unit in perUnit)) throw new Error(`unknown unit ${unit}`);
  return value * perUnit[unit];
}

/** The longest bond line in an Indigo SVG, in the SVG's pixels. Indigo draws each bond line
 * as a stroked path "M x y L x y" in drawing units, scaled by its transform; a bond between
 * two unlabelled carbons is drawn full length, so the longest line is the bond length. */
export function bondLengthInSvg(svg: string): number {
  let longest = 0;
  for (const [path] of svg.matchAll(/<path fill="none"[^>]*>/g)) {
    const line = / d="M ([-\d.]+) ([-\d.]+) L ([-\d.]+) ([-\d.]+) "/.exec(path);
    const scale = / transform="matrix\(([-\d.]+), 0, 0, ([-\d.]+),/.exec(path);
    if (!line || !scale) continue;
    expect(scale[1]).toBe(scale[2]);
    const [x1, y1, x2, y2] = line.slice(1).map(Number);
    longest = Math.max(longest, Math.hypot(x2 - x1, y2 - y1) * Number(scale[1]));
  }
  expect(longest, 'the SVG has bond lines').toBeGreaterThan(0);
  return longest;
}


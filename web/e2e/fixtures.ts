// Fixtures for the smoke tests: a server the test owns, a fresh browser profile, and
// guards that fail the test on page errors, editor errors, CSP violations, popups,
// websockets and same-origin HTTP errors.
//
// Local runs serve DIST_DIR (default dist) at BASE (default staging) with Vite's preview
// server. With SMOKE_URL set, the tests run against that deployed URL instead.
import { test as base, chromium, expect, type BrowserContext, type Page } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { preview } from 'vite';
import { resolveBase } from '../config/app.ts';

const WEB_DIR = fileURLToPath(new URL('..', import.meta.url));
const FIXTURES_DIR = fileURLToPath(new URL('../../tests/fixtures/', import.meta.url));

export interface AppServer {
  /** The app's URL, ending with the base path. */
  url: string;
  /** True when the test controls the server (local runs). */
  local: boolean;
  close(): Promise<void>;
}

export async function startServer(): Promise<AppServer> {
  const remote = process.env.SMOKE_URL;
  if (remote) return { url: remote, local: false, close: async () => {} };
  const server = await preview({
    configFile: false,
    root: WEB_DIR,
    base: resolveBase(),
    // 'mpa': a missing file is a 404, as on Apache, not index.html.
    appType: 'mpa',
    logLevel: 'warn',
    build: { outDir: process.env.DIST_DIR ?? 'dist' },
    preview: { host: '127.0.0.1', port: 0, strictPort: true },
  });
  const url = server.resolvedUrls?.local[0];
  if (!url) throw new Error('preview server did not report a URL');
  return { url, local: true, close: () => server.close() };
}

/** A file from tests/fixtures/ (generated by RDKit or recorded from PubChem). */
export function fixture(rel: string): string {
  return readFileSync(FIXTURES_DIR + rel, 'utf8');
}

export interface ReferenceCompound {
  typed_name: string;
  inchikey: string;
  files: string[];
}

export function referenceCompound(typedName: string): ReferenceCompound {
  const data = JSON.parse(fixture('reference_expected.json')) as { compounds: ReferenceCompound[] };
  const found = data.compounds.find((c) => c.typed_name === typedName);
  if (!found) throw new Error(`${typedName} is not in reference_expected.json`);
  return found;
}

// Runs in every document before any page script.
function installPageGuards() {
  type Report = (kind: string, detail: string) => void;
  const report: Report = (kind, detail) =>
    (window as unknown as { __reportGuard?: Report }).__reportGuard?.(kind, detail);
  addEventListener('securitypolicyviolation', (e) =>
    report('csp', `${e.violatedDirective} blocked ${e.blockedURI}`),
  );
  addEventListener('editor-error', (e) => report('editor-error', String((e as CustomEvent).detail)));
  const once = (name: string) =>
    new Promise<true>((resolve) => addEventListener(name, () => resolve(true), { once: true }));
  Object.assign(window, {
    __editorReady: once('editor-ready'),
    __indigoReady: once('struct-service-initialized'),
  });
}

export interface App {
  server: AppServer;
  context: BrowserContext;
  page: Page;
  /** Every problem the guards saw; the fixture asserts it is empty after the test. */
  problems: string[];
}

export const test = base.extend<{ app: App }>({
  // eslint-disable-next-line no-empty-pattern
  app: async ({}, use, testInfo) => {
    const server = await startServer();
    // A fresh persistent profile: not incognito (Chrome reports 'in-incognito' as not
    // installable) and with no service worker left over from an earlier run.
    const context = await chromium.launchPersistentContext(testInfo.outputPath('profile'), {
      channel: 'chromium',
      headless: true,
    });
    const problems: string[] = [];
    const origin = new URL(server.url).origin;
    await context.exposeFunction('__reportGuard', (kind: string, detail: string) => {
      problems.push(`${kind}: ${detail}`);
    });
    await context.addInitScript(installPageGuards);
    const watch = (page: Page) => {
      page.on('pageerror', (error) => problems.push(`pageerror: ${error.message}`));
      page.on('websocket', (ws) => problems.push(`websocket: ${ws.url()}`));
    };
    const page = context.pages()[0] ?? (await context.newPage());
    watch(page);
    context.on('page', (popup) => {
      problems.push(`popup: ${popup.url()}`);
      watch(popup);
    });
    context.on('response', (response) => {
      if (new URL(response.url()).origin === origin && response.status() >= 400) {
        problems.push(`HTTP ${response.status()}: ${response.url()}`);
      }
    });
    await use({ server, context, page, problems });
    await context.close();
    await server.close();
    expect(problems, 'guards').toEqual([]);
  },
});

/** Load the app and wait until Ketcher and its Indigo engine are both ready. */
export async function openEditor(app: App): Promise<void> {
  await app.page.goto(app.server.url);
  await waitForEditor(app.page);
}

export async function waitForEditor(page: Page): Promise<void> {
  await page.evaluate(() => {
    const w = window as unknown as { __editorReady: Promise<true>; __indigoReady: Promise<true> };
    return Promise.all([w.__editorReady, w.__indigoReady]);
  });
}


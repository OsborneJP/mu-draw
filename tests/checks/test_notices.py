import zipfile
from pathlib import Path

from checks.notices import check

JAR = "server/opsin/opsin.jar"
LISTING = "third_party/opsin/LICENSES.txt"


def write(repo: Path, rel: str, content: str | bytes) -> None:
    path = repo / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(content, bytes):
        path.write_bytes(content)
    else:
        path.write_text(content, encoding="utf-8")


def make_jar(repo: Path, artifacts: dict[str, str], classes: list[str]) -> None:
    """A jar packing these Maven artifacts ('group:artifact' -> version) and classes."""
    path = repo / JAR
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w") as jar:
        for coordinates, version in artifacts.items():
            group, artifact = coordinates.split(":")
            jar.writestr(
                f"META-INF/maven/{group}/{artifact}/pom.properties",
                f"#Generated by Maven\nartifactId={artifact}\ngroupId={group}\nversion={version}\n",
            )
        for name in classes:
            jar.writestr(name, b"\xca\xfe\xba\xbe")


def listed_repo(repo: Path, notices: str = f"Libraries: {LISTING}.\n") -> Path:
    """A repo whose jar is fully listed and whose notices name the listing."""
    make_jar(
        repo, {"org.example:lib": "1.2"}, ["org/example/lib/A.class", "org/example/lib/sub/B.class"]
    )
    write(repo, LISTING, "Maven: org.example:lib 1.2\nClasses: org/example/lib/\n")
    write(repo, "THIRD-PARTY-NOTICES.md", notices)
    return repo


def test_named_data_and_a_listed_jar_pass(repo: Path):
    listed_repo(repo, f"From nmrshiftdb2: data/shifts.json.\nLibraries: {LISTING}.\n")
    write(repo, "data/shifts.json", '{"source": "NMRShiftDB2"}\n')
    assert check(repo) == []


def test_unnamed_nmrshiftdb2_data_fails_text_or_binary(repo: Path):
    listed_repo(repo)
    write(repo, "data/shifts.json", '{"source": "NMRShiftDB2"}\n')
    write(repo, "data/table.bin", b"\x00\xffnmrshiftdb2withsignals.sd\x01")
    assert check(repo) == [
        "data/shifts.json holds nmrshiftdb2 data but THIRD-PARTY-NOTICES.md doesn't name it",
        "data/table.bin holds nmrshiftdb2 data but THIRD-PARTY-NOTICES.md doesn't name it",
    ]


def test_a_longer_path_doesnt_name_a_file(repo: Path):
    listed_repo(repo, f"From nmrshiftdb2: fixtures/proton_nmr/excerpt.sd.\nLibraries: {LISTING}.\n")
    write(repo, "fixtures/proton_nmr/excerpt.sd", "> <nmrshiftdb2 ID>\n")
    write(repo, "nmr/excerpt.sd", "> <nmrshiftdb2 ID>\n")
    assert check(repo) == [
        "nmr/excerpt.sd holds nmrshiftdb2 data but THIRD-PARTY-NOTICES.md doesn't name it"
    ]


def test_a_path_with_more_after_it_doesnt_name_a_file(repo: Path):
    listed_repo(repo, f"From nmrshiftdb2: data/shifts.json-old.\nLibraries: {LISTING}.\n")
    write(repo, "data/shifts.json", '{"source": "NMRShiftDB2"}\n')
    assert check(repo) == [
        "data/shifts.json holds nmrshiftdb2 data but THIRD-PARTY-NOTICES.md doesn't name it"
    ]


def test_code_prose_and_files_that_only_name_it_are_skipped(repo: Path):
    listed_repo(repo)
    write(repo, "web/table.ts", "// Built from NMRShiftDB2\n")
    write(repo, "data/README.md", "Measured shifts come from NMRShiftDB2.\n")
    write(
        repo, "tests/fixtures/nmr_names.txt", "# Measured shifts come from NMRShiftDB2\nethanol\n"
    )
    assert check(repo) == []


def test_an_ignored_file_is_skipped(repo: Path):
    listed_repo(repo)
    write(repo, ".gitignore", "dist/\n")
    write(repo, "dist/nmr/table.bin", b"nmrshiftdb2")
    assert check(repo) == []


def test_an_unlisted_artifact_or_version_fails(repo: Path):
    listed_repo(repo)
    make_jar(
        repo,
        {"org.example:lib": "1.3", "org.other:extra": "4.0"},
        ["org/example/lib/A.class"],
    )
    assert check(repo) == [
        f"{JAR} packs org.example:lib 1.3, which {LISTING} doesn't list",
        f"{JAR} packs org.other:extra 4.0, which {LISTING} doesn't list",
    ]


def test_classes_outside_every_listed_package_fail(repo: Path):
    listed_repo(repo)
    make_jar(
        repo,
        {"org.example:lib": "1.2"},
        [
            "org/example/lib/A.class",
            "org/other/x/C.class",
            "org/other/x/D.class",
            "module-info.class",
        ],
    )
    assert check(repo) == [
        f"{JAR} holds module-info.class, which {LISTING} doesn't list",
        f"{JAR} holds org/other/x/, which {LISTING} doesn't list",
    ]


def test_a_package_that_takes_in_another_listed_one_fails(repo: Path):
    # A library that shades another inside its own package lists only its own packages, so a
    # newly shaded library can't hide under the outer one's line.
    listed_repo(repo)
    make_jar(
        repo,
        {"org.example:lib": "1.2"},
        ["org/example/lib/A.class", "org/example/lib/shaded/x/B.class"],
    )
    write(
        repo,
        LISTING,
        "Maven: org.example:lib 1.2\n"
        "Classes: org/example/lib/\n"
        "Classes: org/example/lib/shaded/x/\n",
    )
    assert check(repo) == [
        f"{LISTING} lists org/example/lib/, which takes in org/example/lib/shaded/x/"
    ]


def test_the_notices_must_name_the_listing(repo: Path):
    listed_repo(repo, "Libraries: see the jar.\n")
    assert check(repo) == [f"THIRD-PARTY-NOTICES.md doesn't name {LISTING}"]


def test_a_missing_listing_or_jar_fails(repo: Path):
    listed_repo(repo)
    (repo / LISTING).unlink()
    assert check(repo) == [f"{LISTING} is missing: it lists what {JAR} packs inside it"]
    (repo / JAR).unlink()
    assert check(repo) == [f"{JAR} is missing"]


def test_missing_notices_fail(repo: Path):
    assert check(repo) == ["THIRD-PARTY-NOTICES.md is missing"]

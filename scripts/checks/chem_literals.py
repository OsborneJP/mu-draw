"""Fail on chemistry file content typed into source code.

Chemistry values come only from RDKit, Ketcher/Indigo, OPSIN or PubChem.
Fixtures generated by those tools live under tests/fixtures/. Source and tests
read them; they never contain Molfile, CDXML, InChI or InChIKey text. A line
that genuinely needs one carries `chem-literal-ok: <reason>`.

SMILES strings can't be told apart from ordinary text reliably, so they are
covered by review only (see AGENTS.md).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from checks.files import read_text, repo_files
from lib.appconfig import ROOT

SOURCE_SUFFIXES = {".py", ".ts", ".tsx", ".js", ".mjs", ".cjs"}
FIXTURE_DIR = "tests/fixtures/"
# Built by concatenation so this file does not match itself.
MARKERS = ("V" + "2000", "V" + "3000", "M" + "  END", "<" + "CDXML", "InChI" + "=")
INCHIKEY = re.compile(r"\b[A-Z]{14}-[A-Z]{10}-[A-Z]\b")
OK_TAG = re.compile(r"chem-literal-ok:\s*\S")


def find(root: Path) -> list[str]:
    problems = []
    for path in repo_files(root):
        rel = path.relative_to(root).as_posix()
        if path.suffix not in SOURCE_SUFFIXES or rel.startswith(FIXTURE_DIR):
            continue
        text = read_text(path)
        if text is None:
            continue
        for lineno, line in enumerate(text.splitlines(), start=1):
            if OK_TAG.search(line):
                continue
            hits = [m for m in MARKERS if m in line]
            if INCHIKEY.search(line):
                hits.append("InChIKey")
            if hits:
                problems.append(f"{rel}:{lineno}: chemistry literal ({', '.join(hits)})")
    return problems


def main(argv: list[str]) -> int:
    root = Path(argv[1]) if len(argv) > 1 else ROOT
    problems = find(root)
    for problem in problems:
        print(problem)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
